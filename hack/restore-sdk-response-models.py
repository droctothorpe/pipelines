"""Restore unchanged stock public Client response models, without REST transports.

The generated model sources are copied byte-for-byte from the contract baseline.
No API service classes, ApiClient, REST transport or server implementation is copied.
"""

import argparse
import ast
import re
import subprocess
from pathlib import Path

BASELINE = '7780f12acfbde9f16169c7fcbfdfb6c3ef5432ea'
ROOT = Path(__file__).resolve().parents[1]
PREFIX = 'sdk/python/kfp/server_api/'
MODEL_ROOTS = {
    'V2Experiment',
    'V2Pipeline',
    'V2PipelineVersion',
    'V2Run',
    'V2RecurringRun',
    'V2ListExperimentsResponse',
    'V2ListPipelinesResponse',
    'V2ListPipelineVersionsResponse',
    'V2ListRunsResponse',
    'V2ListRecurringRunsResponse',
    'V2GetHealthzResponse',
}


def original(ref, path):
    return subprocess.check_output(
        ['git', 'show', f'{ref}:{path}'], cwd=ROOT, text=True
    )


def restore(ref):
    module = ast.parse(original(ref, PREFIX + '__init__.py'))
    models = {
        alias.name: statement.module.removeprefix('kfp.server_api.').replace(
            '.', '/'
        )
        + '.py'
        for statement in module.body
        if isinstance(statement, ast.ImportFrom)
        and statement.module
        and statement.module.startswith('kfp.server_api.models.')
        for alias in statement.names
    }
    roots = set(MODEL_ROOTS)
    client = original(ref, 'sdk/python/kfp/client/client.py')
    roots.update(
        name
        for name in re.findall(r'kfp\.server_api\.([A-Za-z0-9_]+)', client)
        if name in models
    )
    missing = roots - models.keys()
    if missing:
        raise ValueError(
            f'Unknown response types in baseline: {sorted(missing)}'
        )
    pending, sources = list(roots), {}
    while pending:
        name = pending.pop()
        if name in sources:
            continue
        source = original(ref, PREFIX + models[name])
        sources[name] = source
        pending.extend(
            set(re.findall(r'\b[A-Z][A-Za-z0-9_]+\b', source))
            & models.keys() - sources.keys()
        )
    for name, source in sources.items():
        path = ROOT / PREFIX / models[name]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)
    for support in ['configuration.py', 'exceptions.py']:
        path = ROOT / PREFIX / support
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(original(ref, PREFIX + support))
    header = (
        '# Copyright 2026 The Kubeflow Authors\n# SPDX-License-Identifier: Apache-2.0\n'
        '# Generated by hack/restore-sdk-response-models.py; do not edit.\n'
        f'# Public response model definitions copied from {ref}.\n'
    )
    for initializer in ['models/__init__.py', '__init__.py']:
        declarations = []
        for statement in ast.parse(original(ref, PREFIX + initializer)).body:
            if (
                isinstance(statement, ast.ImportFrom)
                and statement.module
                and statement.module.startswith('kfp.server_api.models.')
            ):
                if all(alias.name in sources for alias in statement.names):
                    declarations.append(ast.unparse(statement))
        if initializer == '__init__.py':
            declarations[:0] = [
                'from kfp.version import __version__',
                'from kfp.server_api.configuration import Configuration',
                'from kfp.server_api.exceptions import ApiException, ApiKeyError, ApiTypeError, ApiValueError, OpenApiException',
            ]
        (ROOT / PREFIX / initializer).write_text(
            header + '\n' + '\n'.join(declarations) + '\n'
        )
    return {name: models[name] for name in sorted(sources)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ref', default=BASELINE)
    options = parser.parse_args()
    for name, path in restore(options.ref).items():
        print(
            f'from kfp.server_api.{path.removesuffix(".py").replace("/", ".")} import {name}'
        )


if __name__ == '__main__':
    main()
